"""
agent.py — МОЗГ агента и его ЦИКЛ. Самый важный файл: здесь та самая
"агентность", ради которой всё затевалось.

Идея цикла (agent loop):
    1. Отдаём модели весь разговор + список инструментов.
    2. Модель отвечает одним из двух:
         (а) обычный текст — значит хочет что-то сказать пациенту -> выходим;
         (б) "вызови такой-то инструмент с такими аргументами" -> исполняем
             инструмент, кладём результат в разговор и идём на шаг 1 снова.
    3. Крутимся, пока модель не ответит текстом.

Один "ход" пациента может вызвать несколько инструментов подряд (например:
проверить слоты -> записать) — поэтому это именно ЦИКЛ, а не один вызов.
"""

import os
from openai import OpenAI          # тот же клиент OpenAI — OpenRouter совместим с ним

import tools                       # наши инструменты и их схема

# OpenRouter = единый шлюз к сотням моделей через OpenAI-совместимый API.
# Отличий от чистого OpenAI всего два: другой base_url и другой ключ.
client = OpenAI(
    base_url="https://openrouter.ai/api/v1",           # адрес OpenRouter вместо OpenAI
    api_key=os.environ["OPENROUTER_API_KEY"],          # ключ с openrouter.ai/keys (см. .env.example)
)

# На OpenRouter имя модели идёт с префиксом-вендором: "провайдер/модель".
# Примеры: "openai/gpt-4o", "openai/gpt-4o-mini" (дешевле),
#          "anthropic/claude-3.5-sonnet", "google/gemini-2.0-flash-001".
# ВАЖНО: бери модель, которая поддерживает tools/function calling — иначе
# инструменты работать не будут. У перечисленных выше поддержка есть.
MODEL = "openai/gpt-4o"


# ---------------------------------------------------------------------
# СИСТЕМНЫЙ ПРОМПТ — правила поведения агента. Это НЕ украшение, а основная
# логика: кто он, что должен сделать, какие ограничения. 80% качества — здесь.
# ---------------------------------------------------------------------
SYSTEM_PROMPT = """Ты — администратор стоматологии «Улыбка». Твоя единственная
задача — записать позвонившего пациента на приём. Говори коротко, вежливо,
по-человечески, как живой администратор по телефону.

Правила:
- Узнай, что беспокоит пациента, его имя и телефон.
- Чтобы предложить время, СНАЧАЛА проверь свободные слоты через инструмент
  get_available_slots. Не выдумывай времена сам.
- Перед тем как записать, проговори выбранное время и получи явное «да».
- Записывай через инструмент book_appointment только после подтверждения.
- Не ставь диагнозы и не называй цены — это делает врач на приёме.
- Если пациент грубит или ты дважды не понял его — вежливо предложи, что
  перезвонит администратор, и заверши.
"""


def get_today_hint() -> str:
    """Подсказка модели про текущую дату — иначе она не знает, какое сегодня число
    и что значит 'завтра'. Добавляем к системному промпту."""
    from datetime import datetime
    return f"\nСегодняшняя дата: {datetime.now().strftime('%Y-%m-%d (%A)')}."


def create_conversation() -> list[dict]:
    """Создаёт новый разговор. 'messages' — это ПАМЯТЬ агента: список реплик,
    который мы каждый раз целиком отдаём модели. Начинается с системного промпта."""
    return [{"role": "system", "content": SYSTEM_PROMPT + get_today_hint()}]


def run_turn(messages: list[dict], user_text: str) -> str:
    """Обрабатывает ОДНУ реплику пациента и возвращает ответ агента.

    messages изменяется на месте (mutable) — так разговор копится между ходами.
    """
    # 1. Добавляем реплику пациента в память разговора.
    messages.append({"role": "user", "content": user_text})

    # 2. ЦИКЛ. Крутится, пока модель вызывает инструменты. Ограничим числом
    #    итераций, чтобы не зациклиться, если модель "застрянет".
    for _ in range(10):
        response = client.chat.completions.create(
            model=MODEL,
            messages=messages,           # вся память разговора
            tools=tools.TOOLS_SCHEMA,    # описания инструментов — модель знает, что ей доступно
        )
        message = response.choices[0].message   # что ответила модель на этом шаге

        # Кладём ответ модели в память (даже если это запрос инструмента —
        # его тоже нужно сохранить, иначе следующий вызов будет несогласован).
        messages.append(message)

        # --- Развилка: модель попросила инструмент или просто ответила? ---
        if not message.tool_calls:
            # Инструменты не нужны — это финальный текст для пациента. Выходим.
            return message.content

        # Модель запросила один или несколько инструментов — исполняем каждый.
        for tool_call in message.tool_calls:
            name = tool_call.function.name              # какой инструмент
            args = tool_call.function.arguments         # аргументы (строка JSON)

            result = tools.run_tool(name, args)         # РЕАЛЬНО исполняем у себя

            # Возвращаем результат модели специальным сообщением role="tool".
            # tool_call_id связывает результат с конкретным запросом модели.
            messages.append(
                {
                    "role": "tool",
                    "tool_call_id": tool_call.id,
                    "content": result,
                }
            )
        # ...и идём на следующую итерацию цикла: модель увидит результат
        # инструмента и решит, что делать дальше (позвать ещё инструмент или
        # ответить пациенту).

    # Если за 10 итераций не завершились — что-то пошло не так.
    return "Извините, я немного запутался. Давайте я передам администратору, он перезвонит."
