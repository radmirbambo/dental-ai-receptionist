"""
tools.py — ИНСТРУМЕНТЫ агента (то, что в правой части архитектуры называлось
"FastAPI — инструменты"). Это мост между "думающим" мозгом (LLM) и реальными
действиями с базой.

Здесь две вещи:
  1. TOOLS_SCHEMA — ОПИСАНИЕ инструментов на языке, который понимает LLM.
     Модель читает это описание и решает, какую функцию и с какими аргументами
     вызвать. Она НЕ исполняет код — только говорит "вызови вот это".
  2. Сами функции (execute_*) — реальный Python-код, который мы исполняем,
     когда модель попросила. Он лезет в БД через db.py.

Ключевая идея агентности: модель ВЫБИРАЕТ инструмент, а исполняем его МЫ.
"""

import json
import db                          # наш слой базы из соседнего файла

# У нас одна клиника в MVP. В продакшене clinic_id придёт из контекста звонка
# (на какой номер позвонили — та и клиника).
CLINIC_ID = 1


# ---------------------------------------------------------------------
# 1. СХЕМА ИНСТРУМЕНТОВ — то, что видит LLM.
#    Формат — стандарт OpenAI "tools". Каждый инструмент = имя + описание +
#    параметры (в формате JSON Schema). Описания важны: по ним модель понимает,
#    КОГДА и КАК звать функцию. Пиши их ясно, это часть "программирования" агента.
# ---------------------------------------------------------------------
TOOLS_SCHEMA = [
    {
        "type": "function",
        "function": {
            "name": "get_available_slots",           # имя должно совпадать с ключом в TOOLS ниже
            "description": (
                "Вернуть список свободных времён для записи на приём на указанную "
                "дату. Вызывай, когда нужно предложить пациенту свободное время."
            ),
            "parameters": {
                "type": "object",
                "properties": {
                    "date": {
                        "type": "string",
                        "description": (
                            "Дата в формате YYYY-MM-DD. Можно также передать "
                            "'today' или 'tomorrow', если пациент сказал "
                            "'сегодня'/'завтра'."
                        ),
                    }
                },
                "required": ["date"],                 # без даты вызвать нельзя
            },
        },
    },
    {
        "type": "function",
        "function": {
            "name": "book_appointment",
            "description": (
                "Создать запись пациента на приём. Вызывай ТОЛЬКО после того, "
                "как пациент подтвердил конкретное время, и у тебя есть его имя "
                "и телефон."
            ),
            "parameters": {
                "type": "object",
                "properties": {
                    "patient_name": {"type": "string", "description": "Имя пациента"},
                    "phone": {"type": "string", "description": "Телефон пациента"},
                    "slot": {
                        "type": "string",
                        "description": "Выбранный слот в формате 'YYYY-MM-DD HH:00'",
                    },
                    "reason": {
                        "type": "string",
                        "description": "Что беспокоит пациента (например, 'болит зуб')",
                    },
                },
                "required": ["patient_name", "phone", "slot"],  # reason необязателен
            },
        },
    },
]


# ---------------------------------------------------------------------
# 2. РЕАЛИЗАЦИИ — реальный код инструментов.
#    Каждая принимает распарсенные аргументы и возвращает словарь-результат,
#    который мы отдадим обратно модели. Модель "прочитает" результат и
#    продолжит разговор.
# ---------------------------------------------------------------------
def execute_get_available_slots(date: str) -> dict:
    real_date = db.resolve_date(date)                 # 'tomorrow' -> '2026-07-14'
    slots = db.free_slots_for_date(CLINIC_ID, real_date)
    return {"date": real_date, "free_slots": slots}   # модель увидит список и предложит пациенту


def execute_book_appointment(
    patient_name: str, phone: str, slot: str, reason: str = ""
) -> dict:
    return db.create_appointment(CLINIC_ID, patient_name, phone, slot, reason)


# Таблица соответствия: имя инструмента (как в схеме) -> реальная функция.
# Цикл агента будет искать функцию здесь по имени, которое назвала модель.
TOOLS = {
    "get_available_slots": execute_get_available_slots,
    "book_appointment": execute_book_appointment,
}


def run_tool(name: str, arguments_json: str) -> str:
    """Единая точка исполнения инструмента.

    Модель присылает аргументы СТРОКОЙ с JSON (например '{"date": "tomorrow"}').
    Мы её парсим, находим нужную функцию, вызываем, а результат сериализуем
    обратно в JSON-строку — модель принимает результаты именно так.

    ensure_ascii=False — чтобы русский текст в ответе не превращался в \\uXXXX.
    """
    arguments = json.loads(arguments_json)            # строка JSON -> словарь Python
    func = TOOLS[name]                                # находим реальную функцию по имени
    result = func(**arguments)                        # вызываем, распаковав аргументы
    return json.dumps(result, ensure_ascii=False)     # результат -> JSON-строка для модели
