"""
cli.py — чат с агентом прямо в терминале.

Это самый быстрый способ УВИДЕТЬ цикл "модель -> инструмент -> БД" своими
глазами, без телефонии и голоса. Запусти, поговори как пациент:
    "Здравствуйте, болит зуб, хочу записаться на завтра"
и смотри, как агент проверяет слоты и создаёт запись.

Запуск:  python cli.py
"""

import db                          # чтобы создать таблицу при старте
import agent                       # мозг и цикл


def main():
    db.init_db()                   # создаём таблицу appointments, если её нет
    messages = agent.create_conversation()   # новая память разговора

    print("🦷 Стоматология «Улыбка». Агент на связи. (для выхода: 'выход')\n")
    # Пусть агент поздоровается первым — отправим пустой служебный сигнал.
    print("Агент:", agent.run_turn(messages, "(звонок начался, поздоровайся)"), "\n")

    while True:
        user_text = input("Вы: ").strip()
        if user_text.lower() in ("выход", "exit", "quit"):
            print("Агент: До свидания! Ждём вас.")
            break
        answer = agent.run_turn(messages, user_text)   # один ход диалога
        print("Агент:", answer, "\n")


if __name__ == "__main__":
    main()
